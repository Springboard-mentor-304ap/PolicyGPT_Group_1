    """Preserve existing OTP email behavior for app.api.routes.auth.

    Returns the send_email() result dict so callers can inspect success.
    """
    subject = "PolicyGPT Verification OTP"
    html = f"""
    <div style="font-family: sans-serif; padding: 20px;">
      <h2>PolicyGPT Verification</h2>
      <p>Your verification OTP is: <strong style="font-size: 24px;
        color: #2563eb;">{otp}</strong></p>
      <p>This OTP is valid for 5 minutes.</p>
      <p>Regards,<br>PolicyGPT Team</p>
    </div>
    """
    text = f"Your PolicyGPT verification OTP is: {otp}. Valid for 5 minutes."
    return send_email(recipient_email, subject, html, text_content=text)